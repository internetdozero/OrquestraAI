const CRAFTED = new Set(["groq", "cohere", "aws", "tavily", "together", "exa", "jules"]);

export function BrandIcon({
  presetId,
  size = 32,
}: {
  presetId: string;
  size?: number;
}) {
  if (CRAFTED.has(presetId)) {
    return (
      <Tile size={size} label={`${presetId} logo`} glow={COLORS[presetId] ?? "#A1A1AA"}>
        <CraftedMark presetId={presetId} />
      </Tile>
    );
  }
  const path = PATHS[presetId];
  if (path === undefined) {
    return (
      <svg width={size} height={size} viewBox="0 0 32 32" role="img" aria-label="Custom provider">
        <rect width="32" height="32" rx="8" fill="#27272A" />
        <g stroke="#A1A1AA" strokeWidth="2" fill="none" strokeLinecap="round">
          <circle cx="11" cy="16" r="3.5" />
          <path d="M14.5 16h6m-2-2 2 2-2 2M20.5 11v10" />
        </g>
      </svg>
    );
  }
  const color = COLORS[presetId] ?? "#F4F4F5";
  return (
    <Tile size={size} label={`${presetId} logo`} glow={color}>
      <path d={path} fill={color} />
    </Tile>
  );
}
